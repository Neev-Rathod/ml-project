"""
shared/data_utils.py
====================
Helper functions for fold splitting, Gold/Untrusted pool assignment,
and label encoding – used by WP1 to build the standard splits that all
other WPs load.
"""

import numpy as np
import pandas as pd
from pathlib import Path


# ── Constants ──────────────────────────────────────────────────────────────
SUPERCLASSES = ["NORM", "MI", "STTC", "CD", "HYP"]
CLASS_TO_IDX = {c: i for i, c in enumerate(SUPERCLASSES)}

TRAIN_FOLDS = list(range(1, 9))   # folds 1-8
VAL_FOLD    = 9
TEST_FOLD   = 10


# ── Label helpers ──────────────────────────────────────────────────────────

def encode_labels(label_series: pd.Series) -> np.ndarray:
    """
    Convert a Series of superclass strings to integer indices 0…4.
    Rows with missing / multi-label assignments become -1 (excluded later).

    Parameters
    ----------
    label_series : pd.Series
        Each element is a string like 'NORM' or a list like ['NORM'].

    Returns
    -------
    y : ndarray of shape (n,) with dtype int, -1 for unresolvable rows.
    """
    y = np.full(len(label_series), -1, dtype=int)
    for i, val in enumerate(label_series):
        if isinstance(val, list):
            if len(val) == 1 and val[0] in CLASS_TO_IDX:
                y[i] = CLASS_TO_IDX[val[0]]
        elif isinstance(val, str) and val in CLASS_TO_IDX:
            y[i] = CLASS_TO_IDX[val]
    return y


def assign_gold_untrusted(
    meta: pd.DataFrame,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Split training indices (folds 1-8) into Gold Set and Untrusted Pool
    according to the PTB-XL metadata columns.

    Gold Set  (D_L): validated_by_human == True  (we use all validated records)
    Untrusted (D_U): initial_autogenerated_report == True  OR  not validated

    Parameters
    ----------
    meta : pd.DataFrame
        The full ptbxl_database.csv (index = ecg_id), restricted to
        strat_fold in 1..8 before calling this function.

    Returns
    -------
    gold_mask     : boolean ndarray aligned with meta's index (True = gold)
    untrusted_mask: boolean ndarray aligned with meta's index (True = untrusted)
    """
    gold_mask = meta["validated_by_human"].fillna(False).astype(bool).values
    auto_mask = meta["initial_autogenerated_report"].fillna(False).astype(bool).values
    untrusted_mask = auto_mask | (~gold_mask)
    return gold_mask, untrusted_mask


# ── Standard split loader ──────────────────────────────────────────────────

def load_standard_split(
    features_path: str | Path,
    labels_path: str | Path,
    meta_path: str | Path,
) -> dict:
    """
    Load the pre-computed feature / label arrays produced by WP1 and return
    a dictionary of arrays ready for model training and evaluation.

    Expected files
    --------------
    features_path : .npz with key 'X'   shape (21799, 84)
    labels_path   : .npz with keys 'y', 'fold', 'gold_mask'
    meta_path     : path to ptbxl_database.csv (used for noise flags etc.)

    Returns
    -------
    split : dict with keys
        X_train_L, y_train_L  – Gold Set (folds 1-8, validated)
        X_train_U, y_train_U  – Untrusted Pool (folds 1-8, noisy / unvalidated)
        X_val,     y_val      – Validation set (fold 9)
        X_test,    y_test     – Test set (fold 10, clean)
        feature_names         – list of 84 feature names
    """
    features_path = Path(features_path)
    labels_path   = Path(labels_path)

    feat   = np.load(features_path)
    labels = np.load(labels_path)

    X          = feat["X"]
    y          = labels["y"]
    fold       = labels["fold"]
    gold_mask  = labels["gold_mask"].astype(bool)

    # Remove records with no resolved label
    valid = y != -1
    X, y, fold, gold_mask = X[valid], y[valid], fold[valid], gold_mask[valid]

    train_mask = np.isin(fold, TRAIN_FOLDS)
    val_mask   = fold == VAL_FOLD
    test_mask  = fold == TEST_FOLD

    X_train = X[train_mask]
    y_train = y[train_mask]
    gm_train = gold_mask[train_mask]

    split = {
        "X_train_L": X_train[gm_train],
        "y_train_L": y_train[gm_train],
        "X_train_U": X_train[~gm_train],
        "y_train_U": y_train[~gm_train],   # these are the noisy labels
        "X_val":     X[val_mask],
        "y_val":     y[val_mask],
        "X_test":    X[test_mask],
        "y_test":    y[test_mask],
    }

    if "feature_names" in feat:
        split["feature_names"] = list(feat["feature_names"])

    return split
