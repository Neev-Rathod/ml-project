"""
wp1_data_pipeline/run_wp1.py
=============================
Main entry point for Work Package 1.

What this script does
---------------------
1. Loads PTB-XL metadata (ptbxl_database.csv + scp_statements.csv).
2. Optionally loads raw waveforms and extracts the 84-dim feature vectors.
   (If a cached features.npz already exists it skips extraction.)
3. Saves features.npz and labels.npz to --out_dir so other WPs can load them.
4. Saves split_summary.csv and feature_names.csv for human inspection.
5. Runs the sensor noise & subspace analysis (k-Means purity, PCA scree plot).

Usage
-----
    python run_wp1.py --data_path D:\ml-project\dataset --out_dir ..\outputs\wp1

    # Skip waveform loading if features.npz already exists:
    python run_wp1.py --data_path D:\ml-project\dataset \
                      --out_dir ..\outputs\wp1          \
                      --skip_extraction

Arguments
---------
--data_path       Path to the PTB-XL root directory (required, or set PTBXL_PATH)
--out_dir         Where to save outputs              (default: ..\outputs\wp1)
--sampling_rate   100 or 500                          (default: 100)
--skip_extraction Load pre-existing features.npz instead of re-extracting
--max_records     Limit to first N records (useful for quick smoke-testing)
--seed            Random seed                          (default: 42)
"""

import argparse
import sys
import os
from pathlib import Path

import numpy as np
import pandas as pd

# Allow importing from the project root when run as a script
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from wp1_data_pipeline.loader import load_metadata, load_waveforms
from wp1_data_pipeline.feature_extractor import (
    extract_features_batch,
    feature_names,
)
from wp1_data_pipeline.noise_analysis import run_noise_analysis
from shared.data_utils import encode_labels, assign_gold_untrusted, SUPERCLASSES


def parse_args():
    p = argparse.ArgumentParser(description="WP1 – Data Pipeline & Sensor Noise Analysis")
    p.add_argument("--data_path",       required=False,
                   default=os.environ.get("PTBXL_PATH", ""),
                   help="Path to PTB-XL root (or set PTBXL_PATH env var)")
    p.add_argument("--out_dir",         default=os.path.join("..", "outputs", "wp1"))
    p.add_argument("--sampling_rate",   type=int, default=100, choices=[100, 500])
    p.add_argument("--skip_extraction", action="store_true",
                   help="Load features.npz from out_dir instead of re-extracting")
    p.add_argument("--max_records",     type=int, default=None,
                   help="Limit records for quick testing (e.g. 500)")
    p.add_argument("--seed",            type=int, default=42)
    return p.parse_args()


def _print_split_stats(y, fold, gold_mask):
    """Print a summary table of the data split."""
    from shared.data_utils import TRAIN_FOLDS, VAL_FOLD, TEST_FOLD
    train_mask = np.isin(fold, TRAIN_FOLDS) & (y != -1)
    val_mask   = (fold == VAL_FOLD) & (y != -1)
    test_mask  = (fold == TEST_FOLD) & (y != -1)

    n_train      = train_mask.sum()
    n_gold       = (gold_mask & train_mask).sum()
    n_untrusted  = ((~gold_mask) & train_mask).sum()
    n_val        = val_mask.sum()
    n_test       = test_mask.sum()
    n_excluded   = (y == -1).sum()

    print("\n[WP1] ═══════ Data Split Summary ═══════")
    print(f"  Total records loaded : {len(y)}")
    print(f"  Excluded (no label)  : {n_excluded}")
    print(f"  Training (folds 1-8) : {n_train}")
    print(f"    └─ Gold Set D_L    : {n_gold}  (validated_by_human=True)")
    print(f"    └─ Untrusted D_U   : {n_untrusted}  (autogenerated or unvalidated)")
    print(f"  Validation (fold 9)  : {n_val}")
    print(f"  Test       (fold 10) : {n_test}")
    print()

    # Per-class breakdown for training gold set
    print("  Class distribution in Gold Set D_L (training):")
    y_gold = y[gold_mask & train_mask]
    for ci, cname in enumerate(SUPERCLASSES):
        count = (y_gold == ci).sum()
        pct   = 100.0 * count / max(1, len(y_gold))
        print(f"    {cname:6s} : {count:5d}  ({pct:.1f}%)")
    print()

    # Per-class breakdown for untrusted pool
    print("  Class distribution in Untrusted Pool D_U (training):")
    y_untr = y[(~gold_mask) & train_mask]
    for ci, cname in enumerate(SUPERCLASSES):
        count = (y_untr == ci).sum()
        pct   = 100.0 * count / max(1, len(y_untr))
        print(f"    {cname:6s} : {count:5d}  ({pct:.1f}%)")
    print("[WP1] ════════════════════════════════════\n")


def _save_split_summary(y, fold, gold_mask, out_dir: Path):
    """Save a CSV summarising the data split for human inspection."""
    from shared.data_utils import TRAIN_FOLDS, VAL_FOLD, TEST_FOLD
    rows = []
    for ci, cname in enumerate(SUPERCLASSES):
        train_mask = np.isin(fold, TRAIN_FOLDS) & (y != -1)
        rows.append({
            "class": cname,
            "gold_train":      int(((y == ci) & gold_mask & train_mask).sum()),
            "untrusted_train": int(((y == ci) & (~gold_mask) & train_mask).sum()),
            "val":             int(((y == ci) & (fold == VAL_FOLD) & (y != -1)).sum()),
            "test":            int(((y == ci) & (fold == TEST_FOLD) & (y != -1)).sum()),
        })
    df = pd.DataFrame(rows)
    df.to_csv(out_dir / "split_summary.csv", index=False)
    print(f"[WP1] Saved split summary   → {out_dir / 'split_summary.csv'}")


def _save_feature_names(out_dir: Path):
    """Save a CSV mapping feature index → name and view, for other WPs."""
    names = feature_names()
    df = pd.DataFrame({
        "index":   range(len(names)),
        "name":    names,
        "view":    ["View1_TimeDomain" if i < 42 else "View2_FreqDomain"
                    for i in range(len(names))],
    })
    df.to_csv(out_dir / "feature_names.csv", index=False)
    print(f"[WP1] Saved feature names   → {out_dir / 'feature_names.csv'}")


def main():
    args = parse_args()

    if not args.data_path:
        print("ERROR: Provide --data_path or set PTBXL_PATH environment variable.")
        sys.exit(1)

    data_path = Path(args.data_path)
    out_dir   = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    features_file = out_dir / "features.npz"
    labels_file   = out_dir / "labels.npz"

    # ── Step 1: Load metadata ─────────────────────────────────────────────
    print("[WP1] Loading PTB-XL metadata …")
    meta = load_metadata(data_path)
    print(f"[WP1] {len(meta)} records found.")

    # Diagnostic superclass distribution
    dist = meta["diagnostic_superclass"].value_counts(dropna=False)
    print("[WP1] Diagnostic superclass distribution (full dataset):")
    print(dist.rename_axis("class").reset_index(name="count").to_string(index=False))

    # Sensor noise flag summary
    print("\n[WP1] Sensor artifact flags:")
    for flag in ["baseline_drift", "static_noise", "burst_noise", "electrodes_problems"]:
        n = meta[flag].fillna(False).astype(bool).sum()
        print(f"  {flag:28s}: {n:5d} records ({100.0 * n / len(meta):.1f}%)")

    # Gold / untrusted summary across full dataset
    n_gold_full = meta["validated_by_human"].fillna(False).astype(bool).sum()
    n_auto_full = meta["initial_autogenerated_report"].fillna(False).astype(bool).sum()
    print(f"\n[WP1]   validated_by_human          : {n_gold_full} ({100.0*n_gold_full/len(meta):.1f}%)")
    print(f"[WP1]   initial_autogenerated_report: {n_auto_full} ({100.0*n_auto_full/len(meta):.1f}%)")

    # ── Step 2: Feature extraction (or load cache) ────────────────────────
    if args.skip_extraction and features_file.exists() and labels_file.exists():
        print(f"\n[WP1] Loading cached features from {features_file} …")
        feat_data  = np.load(features_file, allow_pickle=True)
        label_data = np.load(labels_file,   allow_pickle=True)
        X          = feat_data["X"]
        y          = label_data["y"]
        fold       = label_data["fold"]
        gold_mask  = label_data["gold_mask"].astype(bool)
        print(f"[WP1] Loaded X shape: {X.shape}")

    else:
        print("\n[WP1] Extracting features from raw waveforms …")
        if args.max_records:
            print(f"[WP1] (limited to first {args.max_records} records)")
            meta_extract = meta.iloc[: args.max_records]
        else:
            meta_extract = meta

        waveforms = load_waveforms(
            meta_extract, data_path, sampling_rate=args.sampling_rate
        )
        X = extract_features_batch(waveforms, fs=args.sampling_rate)

        # Encode labels
        y    = encode_labels(meta_extract["diagnostic_superclass"])
        fold = meta_extract["strat_fold"].values.astype(int)

        # Build gold / untrusted mask
        # We compute it over all records (not just training folds) so the mask
        # is aligned with X/y/fold row-for-row.
        gold_mask_full, _ = assign_gold_untrusted(meta_extract)
        gold_mask = gold_mask_full

        # ── Safety: replace any NaN / Inf with column medians ────────────
        nan_rows = np.isnan(X).any(axis=1).sum()
        inf_rows = np.isinf(X).any(axis=1).sum()
        if nan_rows > 0 or inf_rows > 0:
            print(f"[WP1] WARNING: {nan_rows} NaN rows, {inf_rows} Inf rows — imputing with column medians")
            for col in range(X.shape[1]):
                bad = ~np.isfinite(X[:, col])
                if bad.any():
                    median_val = np.nanmedian(X[~bad, col])
                    X[bad, col] = median_val if np.isfinite(median_val) else 0.0
        else:
            print("[WP1] No NaN or Inf values in feature matrix.")

        # Save compressed arrays
        fnames = np.array(feature_names())
        np.savez_compressed(
            features_file,
            X=X,
            feature_names=fnames,
        )
        np.savez_compressed(
            labels_file,
            y=y,
            fold=fold,
            gold_mask=gold_mask,
            ecg_ids=meta_extract.index.values,
        )
        print(f"[WP1] Saved features  → {features_file}  shape={X.shape}")
        print(f"[WP1] Saved labels    → {labels_file}")

    # ── Step 3: Print & save split statistics ─────────────────────────────
    _print_split_stats(y, fold, gold_mask)
    _save_split_summary(y, fold, gold_mask, out_dir)
    _save_feature_names(out_dir)

    # ── Save feature statistics for each WP to reference ─────────────────
    names = feature_names()
    stats_df = pd.DataFrame({
        "index":  range(len(names)),
        "name":   names,
        "view":   ["View1" if i < 42 else "View2" for i in range(len(names))],
        "mean":   np.nanmean(X, axis=0).round(6),
        "std":    np.nanstd(X, axis=0).round(6),
        "min":    np.nanmin(X, axis=0).round(6),
        "max":    np.nanmax(X, axis=0).round(6),
    })
    stats_df.to_csv(out_dir / "feature_stats.csv", index=False)
    print(f"[WP1] Saved feature stats   → {out_dir / 'feature_stats.csv'}")

    # Use the meta that was actually used for extraction
    meta_for_analysis = meta.iloc[: args.max_records] if args.max_records else meta

    # ── Step 4: Sensor noise & subspace analysis ──────────────────────────
    print("[WP1] Running sensor noise & subspace analysis …")
    run_noise_analysis(
        X       = X,
        y       = y,
        fold    = fold,
        meta    = meta_for_analysis,
        out_dir = out_dir,
        seed    = args.seed,
    )

    # ── Step 5: Final summary ─────────────────────────────────────────────
    print("\n[WP1] ══════ ALL DONE ══════")
    print(f"[WP1] Outputs written to: {out_dir.resolve()}")
    print("[WP1]")
    print("[WP1] Files for other WPs to load:")
    print(f"[WP1]   features    : {features_file}")
    print(f"[WP1]   labels      : {labels_file}")
    print("[WP1]")
    print("[WP1] How to load in any other WP:")
    print("[WP1]   from shared.data_utils import load_standard_split")
    print("[WP1]   split = load_standard_split(")
    print(f"[WP1]       '{features_file}',")
    print(f"[WP1]       '{labels_file}',")
    print("[WP1]   )")
    print("[WP1]   X_L, y_L = split['X_train_L'], split['y_train_L']  # Gold Set")
    print("[WP1]   X_U, y_U = split['X_train_U'], split['y_train_U']  # Untrusted Pool")
    print("[WP1]   X_val, y_val = split['X_val'], split['y_val']")
    print("[WP1]   X_test, y_test = split['X_test'], split['y_test']")


if __name__ == "__main__":
    main()
